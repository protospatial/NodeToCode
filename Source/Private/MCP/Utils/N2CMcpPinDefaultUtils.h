#pragma once

#include "CoreMinimal.h"

class UEdGraphPin;

/**
 * Writes an input pin's default value the way the editor's pin widgets do, and says whether it took (card 0278).
 *
 * UEdGraphSchema_K2::TrySetDefaultValue returns nothing: it leaves the pin unchanged when IsPinDefaultValid refuses the
 * value. So set-input-pin-value, the Python bridge's SetPinValue and the Set variable node tools first run the
 * schema's own check (GetPinDefaultValuesFromString, then IsPinDefaultValid) and return its message when it refuses;
 * only then do they open their transaction, Modify the node and write. A refused value leaves the pin, the node and the package as they were.
 */
class FN2CMcpPinDefault
{
public:
	/**
	 * Value in the form the schema stores for this pin: booleans from true/false/1/0/yes/no; an enum entry by its name,
	 * its display name or its index, as the entry's name; FVector, FVector2D and FRotator without spaces. Anything else
	 * unchanged. False with OutError for a boolean that is none of those spellings.
	 */
	static bool Normalize(const UEdGraphPin& Pin, const FString& Value, FString& OutValue, FString& OutError);

	/**
	 * Empty when the pin's schema accepts the (normalized) value, else the reason: the schema's IsPinDefaultValid
	 * message, or that an object or class path names nothing that loads (the schema would store None for it).
	 */
	static FString Validate(const UEdGraphPin& Pin, const FString& NormalizedValue);

	/**
	 * Normalize then Validate: the value Write stores, or false with OutError (the reason the pin refuses Value). An
	 * empty Value is always accepted: it resets the pin. Touches nothing, so a caller runs it before it opens its
	 * transaction and has nothing to cancel on a refusal (cancelling a nested transaction cancels the outer one).
	 */
	static bool Prepare(const UEdGraphPin& Pin, const FString& Value, FString& OutPrepared, FString& OutError);

	/**
	 * Modifies the owning node and writes a value Prepare returned through the schema; an empty one resets the pin to
	 * its autogenerated default (the editor's Reset to Default). Does not mark the Blueprint; the caller does
	 * (FN2CMcpBlueprintUtils::MarkModified).
	 */
	static void Write(UEdGraphPin& Pin, const FString& Prepared);

	/** Prepare, then Write when it passed; false with OutError, and the pin and its node untouched, when not */
	static bool Apply(UEdGraphPin& Pin, const FString& Value, FString& OutError);

	/** "Pin '<name>' refused the value '<value>': <reason>. The pin keeps its default '<old>'." */
	static FString RefusalMessage(const UEdGraphPin& Pin, const FString& Value, const FString& Reason, const FString& OldValue);

	/** The pin's default as the tools report it: a text pin's text, else UEdGraphPin::GetDefaultAsString */
	static FString Read(const UEdGraphPin& Pin);
};
