"""Keep NodeToCode's Agent Skills in sync and check them.

Stdlib only; run from anywhere with `python -I Agents/sync_skills.py [--check]`.

The skills are written once, in Agents/claude-code/nodetocode/skills/<name>/ (SKILL.md plus references/). This script

1. regenerates the files copied from the plugin's own sources (GENERATED below: the N2C JSON spec that the
   translation prompts share, Content/Prompting/Shared/N2CJsonSpec.md, as references/n2c-json-spec.md);
2. mirrors the skills folder to .agents/skills/ (read by Codex, GitHub Copilot and other agents that use the
   .agents/skills convention), removing files the source no longer has;
3. checks every skill: the frontmatter follows the Agent Skills specification (agentskills.io/specification: only
   name, description, license, compatibility, metadata and allowed-tools; name 1-64 lowercase letters, digits and
   single hyphens, equal to its folder; description 1-1024 characters; compatibility at most 500), SKILL.md is at
   most 500 lines, every relative link in a skill resolves inside that skill, and every MCP tool a skill names is
   registered in the plugin (REGISTER_MCP_TOOL in Source/Private/MCP/Tools/Implementations), every NodeToCodeTools tool
   it names (`NodeToCodeTools.get_n2c_json`) is a tool of that toolset (Content/Python/nodetocode/toolsets/
   n2c_toolset.py), every Epic tool it names (`BlueprintTools.list_functions`) is one NodeToCode's tool mapping
   (wiki/developers/NodeToCode-and-Epic-Tool-Mapping.md) lists, and every NodeToCode tool it names that UE 5.8 leaves
   to Unreal MCP (the mapping's first column) has one of its Epic counterparts named in the same file (card 0177);
4. checks the Claude Code plugin around the skills (card 0172): every MCP tool its commands (commands/*.md) name is
   registered, .claude-plugin/plugin.json is named nodetocode with the version of NodeToCode.uplugin (VersionName),
   and the local marketplace (Agents/claude-code/.claude-plugin/marketplace.json) and the draft entry for other
   marketplaces (Agents/claude-code/marketplace-entry.json) point at the plugin folder;
5. regenerates the copies UE 5.8's toolset registry serves as Agent Skills (card 0177): for each skill,
   Content/Python/nodetocode/skills/<name>.md holds the SKILL.md body (frontmatter stripped) with the skill's
   references/ files appended (links to them say "appended below"), and skills.json there holds each description.
   Content/Python/nodetocode/skills/__init__.py registers one @agent_skill class per skill from those files; every
   skill must have its class there, and the folder holds nothing else.

With --check nothing is written: it fails when a generated file or the mirror is out of date, or when a check fails.
Exit 0 clean, 1 on any finding (each printed on its own line).

A tool name is any backticked kebab-case word (`get-blueprint-n2cjson`), with or without the client prefixes
`mcp__nodetocode__`, `mcp__plugin_nodetocode_nodetocode__` and `NodeToCode.`, plus any such prefixed name anywhere. Backticked kebab-case words that are
not tools are listed in NOT_TOOLS.
"""
