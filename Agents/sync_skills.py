TOOLSET_NAMED_RE = re.compile(r'\b%s\.([A-Za-z_]\w*)' % TOOLSET_CLASS)
EPIC_NAMED_RE = re.compile(r'\b(%s)\.([A-Za-z_]\w*)' % '|'.join(EPIC_TOOLSETS))
REFERENCE_LINK_RE = re.compile(r'\[([^\]]+)\]\((references/[^)\s#]+)\)')
GENERATED_COMMENT_RE = re.compile(r'\A<!-- Generated by Agents/sync_skills\.py[^\n]*-->\n+')
REGISTRY_CLASS_RE = re.compile(r'\binstructions\s*=\s*_instructions\(\s*[\'"]([a-z0-9-]+)[\'"]\s*\)')


def rel(path):
    """Plugin-relative path for messages (the path itself when it is elsewhere, on another drive included)"""
    try:
        shown = os.path.relpath(path, PLUGIN_ROOT)
    except ValueError:
        return path
    return path if shown.startswith('..') else shown.replace(os.sep, '/')


def read_text(path):
    with open(path, encoding='utf-8') as f:
        return f.read()


def registered_tools(tools_dir=TOOLS_DIR):
    """The MCP tool names the plugin registers: the first TEXT("...") of `FMcpToolDefinition X(` in each .cpp that has
    REGISTER_MCP_TOOL. Returns (names, files without a recognisable definition)."""
    names, unparsed = set(), []
    for root, _dirs, files in os.walk(tools_dir):
        for name in sorted(files):
            if not name.endswith('.cpp'):
                continue
            path = os.path.join(root, name)
            text = read_text(path)
            if 'REGISTER_MCP_TOOL(' not in text:
                continue
            found = DEFINITION_RE.findall(text)
            if found:
                names.update(found)
            else:
                unparsed.append(rel(path))
    return names, unparsed


def toolset_tools(source=TOOLSET_SOURCE):
    """The tool names of the NodeToCodeTools toolset: each method decorated with @toolset_registry.tool_call"""
    return set(TOOLSET_TOOL_RE.findall(read_text(source).replace('\r\n', '\n'))) if os.path.isfile(source) else set()


def epic_mapping(path=EPIC_MAPPING):
    """{NodeToCode tool UE 5.8 leaves to Unreal MCP: {its Epic counterparts as Toolset.tool}} from the mapping page's
    table, where a bare name after a comma belongs to the toolset before it (`BlueprintTools.list_functions`,
    `list_graphs`)"""
    mapping = {}
    if not os.path.isfile(path):
        return mapping
    for line in read_text(path).splitlines():
        cells = [c.strip() for c in line.strip().strip('|').split('|')]
        if len(cells) != 2 or not cells[0].startswith('`'):
            continue
        tool = cells[0].strip('`')
        counterparts, toolset = set(), None
        for part in BACKTICK_RE.findall(cells[1]):
            if '.' in part:
                toolset, _sep, name = part.partition('.')
            else:
                name = part
            if toolset:
                counterparts.add('%s.%s' % (toolset, name))
        if TOOL_NAME_RE.match(tool) and counterparts:
            mapping[tool] = counterparts
    return mapping


def parse_frontmatter(text):
    """The subset of YAML SKILL.md frontmatter uses: `key: value` lines (value plain, or in double or single quotes)
    and one level of `key:` followed by indented `sub: value` lines. Returns (fields, body, errors)."""
    if not text.startswith('---\n'):
        return None, text, ['SKILL.md must start with a "---" line (frontmatter)']
    end = text.find('\n---\n', 4)
    if end < 0:
        return None, text, ['frontmatter has no closing "---" line']
    block, body = text[4:end], text[end + 5:]
    fields, errors, current = {}, [], None
    for number, line in enumerate(block.split('\n'), 2):
        if not line.strip() or line.lstrip().startswith('#'):
            continue
        indented = line[0] in ' \t'
        match = re.match(r'^\s*([A-Za-z0-9_-]+):(?:\s+(.*))?$', line)
        if not match:
            errors.append('frontmatter line %d is not "key: value": %r' % (number, line))
            continue
        key, value = match.group(1), (match.group(2) or '').strip()
        if value and value[0] in '"\'':
            if len(value) < 2 or value[-1] != value[0]:
                errors.append('frontmatter line %d: unterminated quoted value' % number)
                continue
            quote, value = value[0], value[1:-1]
            value = value.replace('\\"', '"').replace('\\\\', '\\') if quote == '"' else value.replace("''", "'")
        elif value.startswith(('[', '{', '|', '>')):
            errors.append('frontmatter line %d: use a plain or quoted string for %s' % (number, key))
        elif ': ' in value or value.endswith(':') or ' #' in value:
            errors.append('frontmatter line %d: quote the value of %s (it holds ": " or " #")' % (number, key))
        if indented:
            if current is None:
                errors.append('frontmatter line %d is indented under nothing' % number)
            else:
                fields[current][key] = value
            continue
        if key in fields:
            errors.append('frontmatter key %s appears twice' % key)
        if value == '':
            fields[key], current = {}, key
        else:
            fields[key], current = value, None
    return fields, body, errors


def check_skill(skill_dir, tools, known_names=(), toolset=None, epic=None):
    """Findings for one skill folder. toolset: NodeToCodeTools' tool names (None skips that check); epic: the
    mapping from epic_mapping() (None skips the Epic checks)"""
    name = os.path.basename(skill_dir)
    where = rel(skill_dir)
    path = os.path.join(skill_dir, 'SKILL.md')
    if not os.path.isfile(path):
        return ['%s: no SKILL.md' % where]
    text = read_text(path).replace('\r\n', '\n')
    fields, body, errors = parse_frontmatter(text)
    findings = ['%s/SKILL.md: %s' % (where, e) for e in errors]
    if fields is None:
        return findings
    for key in fields:
        if key not in ALLOWED_FIELDS:
            findings.append('%s/SKILL.md: frontmatter field %s is not in the Agent Skills spec (%s)'
                            % (where, key, ', '.join(ALLOWED_FIELDS)))
    value = fields.get('name')
    if not isinstance(value, str) or not value:
        findings.append('%s/SKILL.md: name is missing' % where)
    else:
        if len(value) > 64 or not NAME_RE.match(value):
            findings.append('%s/SKILL.md: name %r must be 1-64 lowercase letters, digits and single hyphens' % (where, value))
        if value != name:
            findings.append('%s/SKILL.md: name %r does not match its folder %r' % (where, value, name))
    value = fields.get('description')
    if not isinstance(value, str) or not value.strip():
        findings.append('%s/SKILL.md: description is missing' % where)
    elif len(value) > 1024:
        findings.append('%s/SKILL.md: description is %d characters (at most 1024)' % (where, len(value)))
    value = fields.get('compatibility')
    if value is not None and (not isinstance(value, str) or not 1 <= len(value) <= 500):
        findings.append('%s/SKILL.md: compatibility must be a string of 1-500 characters' % where)
    if 'metadata' in fields and not isinstance(fields['metadata'], dict):
        findings.append('%s/SKILL.md: metadata must be a map of strings' % where)
    for key in ('license', 'allowed-tools'):
        if key in fields and not isinstance(fields[key], str):
            findings.append('%s/SKILL.md: %s must be a string' % (where, key))
    lines = text.count('\n') + (0 if text.endswith('\n') else 1)
    if lines > MAX_SKILL_LINES:
        findings.append('%s/SKILL.md: %d lines (keep it at most %d; move detail to references/)'
                        % (where, lines, MAX_SKILL_LINES))

    for root, _dirs, files in os.walk(skill_dir):
        for file_name in sorted(files):
            if not file_name.endswith('.md'):
                continue
            file_path = os.path.join(root, file_name)
            content = read_text(file_path)
            shown = rel(file_path)
            for target in LINK_RE.findall(content):
                if re.match(r'^[a-z]+:', target) or target.startswith('#'):
                    continue
                resolved = os.path.normpath(os.path.join(os.path.dirname(file_path), target.split('#')[0]))
                if not resolved.startswith(os.path.normpath(skill_dir) + os.sep) or not os.path.exists(resolved):
                    findings.append('%s: link %s does not resolve to a file inside the skill' % (shown, target))
            named = named_tools(content)
            for tool in sorted(named - tools - NOT_TOOLS - set(known_names)):
                findings.append('%s: names MCP tool %r, which the plugin does not register' % (shown, tool))
            findings += check_tool_routes(shown, content, named, toolset, epic)
    return findings


def check_tool_routes(shown, content, named, toolset, epic):
    """Findings for the NodeToCodeTools and Epic tools a skill file names (see the module docstring)"""
    findings = []
    if toolset is not None:
        for tool in sorted(set(TOOLSET_NAMED_RE.findall(content)) - toolset):
            findings.append('%s: names %s.%s, which is not a tool of the %s toolset'
                            % (shown, TOOLSET_CLASS, tool, TOOLSET_CLASS))
    if epic is not None:
        known = set().union(*epic.values()) if epic else set()
        epic_named = {'%s.%s' % m for m in EPIC_NAMED_RE.findall(content)}
        for tool in sorted(epic_named - known):
            findings.append('%s: names Epic tool %s, which NodeToCode\'s tool mapping does not list' % (shown, tool))
        for tool in sorted(named & set(epic)):
            if not epic[tool] & epic_named:
                findings.append('%s: names %r, which UE 5.8 leaves to Unreal MCP, without its Epic counterpart (%s)'
                                % (shown, tool, ', '.join(sorted(epic[tool]))))
    return findings


def named_tools(text):
    """Tool-like names a skill text uses (see the module docstring)"""
    names = set(PREFIXED_RE.findall(text))
    for token in BACKTICK_RE.findall(text):
        token = token.strip()
        for prefix in TOOL_PREFIXES:
            if token.startswith(prefix):
                token = token[len(prefix):]
                break
        if TOOL_NAME_RE.match(token):
            names.add(token)
    return names


def skill_names(skills_dir=SKILLS_DIR):
    return {d for d in os.listdir(skills_dir) if os.path.isdir(os.path.join(skills_dir, d))} if os.path.isdir(skills_dir) else set()


def expected_generated():
    """{absolute path in the source skills: expected text}"""
    out = {}
    for (skill, inner), source in GENERATED.items():
        text = read_text(os.path.join(PLUGIN_ROOT, source)).replace('\r\n', '\n')
        out[os.path.join(SKILLS_DIR, skill, *inner.split('/'))] = GENERATED_HEADER % source + text
    return out


def tree(directory):
    """{relative path: bytes} of every file under directory"""
    out = {}
    if os.path.isdir(directory):
        for root, _dirs, files in os.walk(directory):
            for name in files:
                path = os.path.join(root, name)
                with open(path, 'rb') as f:
                    out[os.path.relpath(path, directory).replace(os.sep, '/')] = f.read()
    return out


def lf(data):
    """data with CRLF line ends made LF, so a checkout with core.autocrlf compares equal (None stays None)"""
    return None if data is None else data.replace(b'\r\n', b'\n')


def write_bytes(path, data):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, 'wb') as f:
        f.write(data)


def registry_instructions(skill_dir):
    """The text UE 5.8's registry serves as a skill's instructions: the SKILL.md body without frontmatter, links to
    references/ files pointed below, and each references/ file appended under its own heading"""
    text = read_text(os.path.join(skill_dir, 'SKILL.md')).replace('\r\n', '\n')
    _fields, body, _errors = parse_frontmatter(text)
    body = REFERENCE_LINK_RE.sub(r'\2 (appended below)', body).strip('\n') + '\n'
    references = os.path.join(skill_dir, 'references')
    if os.path.isdir(references):
        for name in sorted(os.listdir(references)):
            if name.endswith('.md'):
                ref = GENERATED_COMMENT_RE.sub('', read_text(os.path.join(references, name)).replace('\r\n', '\n'))
                body += '\n---\n\n# Appended: references/%s\n\n%s' % (name, ref.strip('\n') + '\n')
    return body


def expected_registry(skills_dir=SKILLS_DIR):
    """{file name in Content/Python/nodetocode/skills: expected text} for every generated file there"""
    out, descriptions = {}, {}
    for name in sorted(skill_names(skills_dir)):
        skill_dir = os.path.join(skills_dir, name)
        if not os.path.isfile(os.path.join(skill_dir, 'SKILL.md')):
            continue
        fields, _body, _errors = parse_frontmatter(read_text(os.path.join(skill_dir, 'SKILL.md')).replace('\r\n', '\n'))
        descriptions[name] = {'description': (fields or {}).get('description', '')}
        out[name + '.md'] = registry_instructions(skill_dir)
    out[REGISTRY_DESCRIPTIONS] = json.dumps(descriptions, indent=2, ensure_ascii=False) + '\n'
    return out


def check_registry_classes(registry_dir=REGISTRY_SKILLS_DIR, skills_dir=SKILLS_DIR):
    """Findings when a skill has no @agent_skill class in the registry package, or a class reads a skill that does
    not exist"""
    path = os.path.join(registry_dir, REGISTRY_INIT)
    if not os.path.isfile(path):
        return ['%s is missing' % rel(path)]
    classes = REGISTRY_CLASS_RE.findall(read_text(path))
    names = skill_names(skills_dir)
    findings = ['%s: no @agent_skill class reads skill %r' % (rel(path), n) for n in sorted(names - set(classes))]
    findings += ['%s: a class reads skill %r, which does not exist' % (rel(path), n)
                 for n in sorted(set(classes) - names)]
    findings += ['%s: more than one class reads skill %r' % (rel(path), n) for n in sorted(set(classes))
                 if classes.count(n) > 1]
    return findings


def sync_registry(check, registry_dir=REGISTRY_SKILLS_DIR, skills_dir=SKILLS_DIR):
    """Writes (or, with check, compares) the registry copies; removes (or reports) any other file there"""
    findings = []
    expected = expected_registry(skills_dir)
    for name, text in sorted(expected.items()):
        path = os.path.join(registry_dir, name)
        current = None
        if os.path.isfile(path):
            with open(path, 'rb') as f:
                current = f.read()
        if lf(current) != text.encode('utf-8'):
            if check:
                findings.append('%s is out of date with the skills source: run python -I Agents/sync_skills.py'
                                % rel(path))
            else:
                write_bytes(path, text.encode('utf-8'))
                print('wrote %s' % rel(path))
    if os.path.isdir(registry_dir):
        for name in sorted(os.listdir(registry_dir)):
            path = os.path.join(registry_dir, name)
            if name in expected or name in (REGISTRY_INIT, '__pycache__'):
                continue
            if check or not os.path.isfile(path) or not name.endswith(('.md', '.json')):
                findings.append('%s is not generated from a skill: remove it' % rel(path))
            else:
                os.remove(path)
                print('removed %s' % rel(path))
    return findings + check_registry_classes(registry_dir, skills_dir)


def sync(check):
    findings = []
    for path, text in expected_generated().items():
        data = text.encode('utf-8')
        current = None
        if os.path.isfile(path):
            with open(path, 'rb') as f:
                current = f.read()
        if lf(current) != data:
            if check:
                findings.append('%s is out of date with its source: run python -I Agents/sync_skills.py' % rel(path))
            else:
                write_bytes(path, data)
                print('wrote %s' % rel(path))

    source, mirror = tree(SKILLS_DIR), tree(MIRROR_DIR)
    for name, data in sorted(source.items()):
        if lf(mirror.get(name)) != lf(data):
            if check:
                findings.append('.agents/skills/%s differs from the skills source: run python -I Agents/sync_skills.py' % name)
            else:
                write_bytes(os.path.join(MIRROR_DIR, *name.split('/')), data)
                print('mirrored .agents/skills/%s' % name)
    for name in sorted(set(mirror) - set(source)):
        if check:
            findings.append('.agents/skills/%s is not in the skills source: run python -I Agents/sync_skills.py' % name)
        else:
            os.remove(os.path.join(MIRROR_DIR, *name.split('/')))
            print('removed .agents/skills/%s' % name)
    if not check and os.path.isdir(MIRROR_DIR):
        for root, dirs, files in os.walk(MIRROR_DIR, topdown=False):
            if not dirs and not files and root != MIRROR_DIR:
                os.rmdir(root)
    return findings + sync_registry(check)


def check_all(skills_dir=SKILLS_DIR, tools_dir=TOOLS_DIR, toolset_source=TOOLSET_SOURCE, mapping=EPIC_MAPPING):
    tools, unparsed = registered_tools(tools_dir)
    findings = ['%s registers a tool whose name this script cannot read' % f for f in unparsed]
    if not tools:
        findings.append('no registered MCP tools found under %s' % rel(tools_dir))
    toolset = toolset_tools(toolset_source)
    if not toolset:
        findings.append('no %s tools found in %s' % (TOOLSET_CLASS, rel(toolset_source)))
    epic = epic_mapping(mapping)
    if not epic:
        findings.append('no NodeToCode-to-Epic tool mapping found in %s' % rel(mapping))
    names = sorted(skill_names(skills_dir))
    if not names:
        findings.append('no skills under %s' % rel(skills_dir))
    for name in names:
        findings += check_skill(os.path.join(skills_dir, name), tools, names, toolset, epic)
    return findings, tools, names


def read_json(path, findings):
    try:
        with open(path, encoding='utf-8') as f:
            return json.load(f)
    except (OSError, ValueError) as e:
        findings.append('%s: cannot read it as JSON (%s)' % (rel(path), e))
        return None


def check_claude_plugin(plugin_dir=CLAUDE_PLUGIN_DIR, tools=None, uplugin=UPLUGIN):
    """Findings for the Claude Code plugin around the skills (see the module docstring)"""
    findings = []
    if tools is None:
        tools, _unparsed = registered_tools()
    commands = os.path.join(plugin_dir, 'commands')
    if os.path.isdir(commands):
        for name in sorted(os.listdir(commands)):
            if name.endswith('.md'):
                path = os.path.join(commands, name)
                for tool in sorted(named_tools(read_text(path)) - tools - NOT_TOOLS):
                    findings.append('%s: names MCP tool %r, which the plugin does not register' % (rel(path), tool))
    manifest = read_json(os.path.join(plugin_dir, '.claude-plugin', 'plugin.json'), findings)
    descriptor = read_json(uplugin, findings)
    if manifest is not None:
        if manifest.get('name') != CLAUDE_PLUGIN_NAME:
            findings.append('%s/.claude-plugin/plugin.json: name must be %r' % (rel(plugin_dir), CLAUDE_PLUGIN_NAME))
        if descriptor is not None and manifest.get('version') != descriptor.get('VersionName'):
            findings.append('%s/.claude-plugin/plugin.json: version %r differs from NodeToCode.uplugin VersionName %r'
                            % (rel(plugin_dir), manifest.get('version'), descriptor.get('VersionName')))
    folder = os.path.basename(os.path.normpath(plugin_dir))
    marketplace_dir = os.path.dirname(os.path.normpath(plugin_dir))
    market = read_json(os.path.join(marketplace_dir, '.claude-plugin', 'marketplace.json'), findings)
    if market is not None:
        entries = [p for p in market.get('plugins') or [] if p.get('name') == CLAUDE_PLUGIN_NAME]
        if len(entries) != 1 or entries[0].get('source') != './' + folder:
            findings.append('%s/.claude-plugin/marketplace.json: needs one %r entry with source "./%s"'
                            % (rel(marketplace_dir), CLAUDE_PLUGIN_NAME, folder))
    entry = read_json(os.path.join(marketplace_dir, 'marketplace-entry.json'), findings)
    if entry is not None:
        source = entry.get('source') if isinstance(entry.get('source'), dict) else {}
        want = 'Agents/claude-code/' + folder  # the plugin folder's path in the NodeToCode repository
        if (entry.get('name') != CLAUDE_PLUGIN_NAME or source.get('source') != 'git-subdir'
                or source.get('path') != want):
            findings.append('%s/marketplace-entry.json: needs name %r and a git-subdir source with path %r'
                            % (rel(marketplace_dir), CLAUDE_PLUGIN_NAME, want))
    return findings


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument('--check', action='store_true', help='write nothing; fail when anything is out of date or invalid')
    args = ap.parse_args(argv)
    findings = sync(args.check)
    more, tools, names = check_all()
    findings += more
    findings += check_claude_plugin(tools=tools)
    for finding in findings:
        print(finding)
    print('%s: %d skills (%s), %d registered MCP tools, %d findings'
          % ('check' if args.check else 'sync', len(names), ', '.join(names), len(tools), len(findings)))
    return 1 if findings else 0


if __name__ == '__main__':
    sys.exit(main())
