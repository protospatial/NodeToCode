CLAUDE_PLUGIN_NAME = 'nodetocode'
MIRROR_DIR = os.path.join(PLUGIN_ROOT, '.agents', 'skills')
TOOLS_DIR = os.path.join(PLUGIN_ROOT, 'Source', 'Private', 'MCP', 'Tools', 'Implementations')
SPEC_SOURCE = 'Content/Prompting/Shared/N2CJsonSpec.md'
REGISTRY_SKILLS_DIR = os.path.join(PLUGIN_ROOT, 'Content', 'Python', 'nodetocode', 'skills')
REGISTRY_INIT = '__init__.py'
REGISTRY_DESCRIPTIONS = 'skills.json'
TOOLSET_SOURCE = os.path.join(PLUGIN_ROOT, 'Content', 'Python', 'nodetocode', 'toolsets', 'n2c_toolset.py')
