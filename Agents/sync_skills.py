"""Keep NodeToCode's Agent Skills in sync and check them.

Stdlib only; run from anywhere with `python -I Agents/sync_skills.py [--check]`.

The skills are written once, in Agents/claude-code/nodetocode/skills/<name>/ (SKILL.md plus references/). This script

1. regenerates the files copied from the plugin's own sources (GENERATED below: the N2C JSON spec that the
   translation prompts share, Content/Prompting/Shared/N2CJsonSpec.md, as references/n2c-json-spec.md);
2. mirrors the skills folder to .agents/skills/ (read by Codex, GitHub Copilot and other agents that use the
   .agents/skills convention), removing files the source no longer has;
3. checks every skill: the frontmatter follows the Agent Skills specification (agentskills.io/specification: only
   name, description, license, compatibility, metadata and allowed-tools; name 1-64 lowercase letters, digits and
   single hyphens, equal to its folder; description 1-1024 characters; compatibility at most 500), SKILL.md is at
   most 500 lines, every relative link in a skill resolves inside that skill, and every MCP tool a skill names is
   registered in the plugin (REGISTER_MCP_TOOL in Source/Private/MCP/Tools/Implementations).

With --check nothing is written: it fails when a generated file or the mirror is out of date, or when a check fails.
Exit 0 clean, 1 on any finding (each printed on its own line).

A tool name is any backticked kebab-case word (`get-blueprint-n2cjson`), with or without the client prefixes
`mcp__nodetocode__` and `NodeToCode.`, plus any mcp__nodetocode__<name> anywhere. Backticked kebab-case words that are
not tools are listed in NOT_TOOLS.
"""
import argparse
import os
import re
import sys

PLUGIN_ROOT = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..'))
SKILLS_DIR = os.path.join(PLUGIN_ROOT, 'Agents', 'claude-code', 'nodetocode', 'skills')
MIRROR_DIR = os.path.join(PLUGIN_ROOT, '.agents', 'skills')
TOOLS_DIR = os.path.join(PLUGIN_ROOT, 'Source', 'Private', 'MCP', 'Tools', 'Implementations')
SPEC_SOURCE = 'Content/Prompting/Shared/N2CJsonSpec.md'

# (skill, file inside the skill) -> plugin-relative source. The copy gets GENERATED_HEADER on top.
GENERATED = {
    ('blueprint-comprehension', 'references/n2c-json-spec.md'): SPEC_SOURCE,
    ('blueprint-to-cpp', 'references/n2c-json-spec.md'): SPEC_SOURCE,
}
GENERATED_HEADER = ('<!-- Generated by Agents/sync_skills.py from the NodeToCode plugin\'s %s. Edit that file and run '
                    'the script; do not edit this copy. -->\n\n')

ALLOWED_FIELDS = ('name', 'description', 'license', 'compatibility', 'metadata', 'allowed-tools')
NAME_RE = re.compile(r'^[a-z0-9]+(-[a-z0-9]+)*$')
MAX_SKILL_LINES = 500
# Claude Code truncates description (+ when_to_use) at 1536 characters in its listing; the spec's 1024 is stricter

# Backticked kebab-case words in the skills that are not MCP tools
NOT_TOOLS = {'allowed-tools'}

TOOL_NAME_RE = re.compile(r'^[a-z][a-z0-9]*(?:-[a-z0-9]+)+$')
BACKTICK_RE = re.compile(r'`([^`\n]+)`')
PREFIXED_RE = re.compile(r'mcp__nodetocode__([A-Za-z0-9_-]+)')
LINK_RE = re.compile(r'\]\(([^)\s]+)\)')
DEFINITION_RE = re.compile(r'FMcpToolDefinition\s+\w+\s*\(\s*TEXT\(\s*"([^"]+)"\s*\)')


def rel(path):
    """Plugin-relative path for messages (the path itself when it is elsewhere, on another drive included)"""
    try:
        shown = os.path.relpath(path, PLUGIN_ROOT)
    except ValueError:
        return path
    return path if shown.startswith('..') else shown.replace(os.sep, '/')


def read_text(path):
    with open(path, encoding='utf-8') as f:
        return f.read()


def registered_tools(tools_dir=TOOLS_DIR):
    """The MCP tool names the plugin registers: the first TEXT("...") of `FMcpToolDefinition X(` in each .cpp that has
    REGISTER_MCP_TOOL. Returns (names, files without a recognisable definition)."""
    names, unparsed = set(), []
    for root, _dirs, files in os.walk(tools_dir):
        for name in sorted(files):
            if not name.endswith('.cpp'):
                continue
            path = os.path.join(root, name)
            text = read_text(path)
            if 'REGISTER_MCP_TOOL(' not in text:
                continue
            found = DEFINITION_RE.findall(text)
            if found:
                names.update(found)
            else:
                unparsed.append(rel(path))
    return names, unparsed


def parse_frontmatter(text):
    """The subset of YAML SKILL.md frontmatter uses: `key: value` lines (value plain, or in double or single quotes)
    and one level of `key:` followed by indented `sub: value` lines. Returns (fields, body, errors)."""
    if not text.startswith('---\n'):
        return None, text, ['SKILL.md must start with a "---" line (frontmatter)']
    end = text.find('\n---\n', 4)
    if end < 0:
        return None, text, ['frontmatter has no closing "---" line']
    block, body = text[4:end], text[end + 5:]
    fields, errors, current = {}, [], None
    for number, line in enumerate(block.split('\n'), 2):
        if not line.strip() or line.lstrip().startswith('#'):
            continue
        indented = line[0] in ' \t'
        match = re.match(r'^\s*([A-Za-z0-9_-]+):(?:\s+(.*))?$', line)
        if not match:
            errors.append('frontmatter line %d is not "key: value": %r' % (number, line))
            continue
        key, value = match.group(1), (match.group(2) or '').strip()
        if value and value[0] in '"\'':
            if len(value) < 2 or value[-1] != value[0]:
                errors.append('frontmatter line %d: unterminated quoted value' % number)
                continue
            quote, value = value[0], value[1:-1]
            value = value.replace('\\"', '"').replace('\\\\', '\\') if quote == '"' else value.replace("''", "'")
        elif value.startswith(('[', '{', '|', '>')):
            errors.append('frontmatter line %d: use a plain or quoted string for %s' % (number, key))
        elif ': ' in value or value.endswith(':') or ' #' in value:
            errors.append('frontmatter line %d: quote the value of %s (it holds ": " or " #")' % (number, key))
        if indented:
            if current is None:
                errors.append('frontmatter line %d is indented under nothing' % number)
            else:
                fields[current][key] = value
            continue
        if key in fields:
            errors.append('frontmatter key %s appears twice' % key)
        if value == '':
            fields[key], current = {}, key
        else:
            fields[key], current = value, None
    return fields, body, errors


def check_skill(skill_dir, tools, known_names=()):
    """Findings for one skill folder"""
    name = os.path.basename(skill_dir)
    where = rel(skill_dir)
    path = os.path.join(skill_dir, 'SKILL.md')
    if not os.path.isfile(path):
        return ['%s: no SKILL.md' % where]
    text = read_text(path).replace('\r\n', '\n')
    fields, body, errors = parse_frontmatter(text)
    findings = ['%s/SKILL.md: %s' % (where, e) for e in errors]
    if fields is None:
        return findings
    for key in fields:
        if key not in ALLOWED_FIELDS:
            findings.append('%s/SKILL.md: frontmatter field %s is not in the Agent Skills spec (%s)'
                            % (where, key, ', '.join(ALLOWED_FIELDS)))
    value = fields.get('name')
    if not isinstance(value, str) or not value:
        findings.append('%s/SKILL.md: name is missing' % where)
    else:
        if len(value) > 64 or not NAME_RE.match(value):
            findings.append('%s/SKILL.md: name %r must be 1-64 lowercase letters, digits and single hyphens' % (where, value))
        if value != name:
            findings.append('%s/SKILL.md: name %r does not match its folder %r' % (where, value, name))
    value = fields.get('description')
    if not isinstance(value, str) or not value.strip():
        findings.append('%s/SKILL.md: description is missing' % where)
    elif len(value) > 1024:
        findings.append('%s/SKILL.md: description is %d characters (at most 1024)' % (where, len(value)))
    value = fields.get('compatibility')
    if value is not None and (not isinstance(value, str) or not 1 <= len(value) <= 500):
        findings.append('%s/SKILL.md: compatibility must be a string of 1-500 characters' % where)
    if 'metadata' in fields and not isinstance(fields['metadata'], dict):
        findings.append('%s/SKILL.md: metadata must be a map of strings' % where)
    for key in ('license', 'allowed-tools'):
        if key in fields and not isinstance(fields[key], str):
            findings.append('%s/SKILL.md: %s must be a string' % (where, key))
    lines = text.count('\n') + (0 if text.endswith('\n') else 1)
    if lines > MAX_SKILL_LINES:
        findings.append('%s/SKILL.md: %d lines (keep it at most %d; move detail to references/)'
                        % (where, lines, MAX_SKILL_LINES))

    for root, _dirs, files in os.walk(skill_dir):
        for file_name in sorted(files):
            if not file_name.endswith('.md'):
                continue
            file_path = os.path.join(root, file_name)
            content = read_text(file_path)
            shown = rel(file_path)
            for target in LINK_RE.findall(content):
                if re.match(r'^[a-z]+:', target) or target.startswith('#'):
                    continue
                resolved = os.path.normpath(os.path.join(os.path.dirname(file_path), target.split('#')[0]))
                if not resolved.startswith(os.path.normpath(skill_dir) + os.sep) or not os.path.exists(resolved):
                    findings.append('%s: link %s does not resolve to a file inside the skill' % (shown, target))
            for tool in sorted(named_tools(content) - tools - NOT_TOOLS - set(known_names)):
                findings.append('%s: names MCP tool %r, which the plugin does not register' % (shown, tool))
    return findings


def named_tools(text):
    """Tool-like names a skill text uses (see the module docstring)"""
    names = set(PREFIXED_RE.findall(text))
    for token in BACKTICK_RE.findall(text):
        token = token.strip()
        for prefix in ('mcp__nodetocode__', 'NodeToCode.'):
            if token.startswith(prefix):
                token = token[len(prefix):]
        if TOOL_NAME_RE.match(token):
            names.add(token)
    return names


def skill_names(skills_dir=SKILLS_DIR):
    return {d for d in os.listdir(skills_dir) if os.path.isdir(os.path.join(skills_dir, d))} if os.path.isdir(skills_dir) else set()


def expected_generated():
    """{absolute path in the source skills: expected text}"""
    out = {}
    for (skill, inner), source in GENERATED.items():
        text = read_text(os.path.join(PLUGIN_ROOT, source)).replace('\r\n', '\n')
        out[os.path.join(SKILLS_DIR, skill, *inner.split('/'))] = GENERATED_HEADER % source + text
    return out


def tree(directory):
    """{relative path: bytes} of every file under directory"""
    out = {}
    if os.path.isdir(directory):
        for root, _dirs, files in os.walk(directory):
            for name in files:
                path = os.path.join(root, name)
                with open(path, 'rb') as f:
                    out[os.path.relpath(path, directory).replace(os.sep, '/')] = f.read()
    return out


def lf(data):
    """data with CRLF line ends made LF, so a checkout with core.autocrlf compares equal (None stays None)"""
    return None if data is None else data.replace(b'\r\n', b'\n')


def write_bytes(path, data):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, 'wb') as f:
        f.write(data)


def sync(check):
    findings = []
    for path, text in expected_generated().items():
        data = text.encode('utf-8')
        current = None
        if os.path.isfile(path):
            with open(path, 'rb') as f:
                current = f.read()
        if lf(current) != data:
            if check:
                findings.append('%s is out of date with its source: run python -I Agents/sync_skills.py' % rel(path))
            else:
                write_bytes(path, data)
                print('wrote %s' % rel(path))

    source, mirror = tree(SKILLS_DIR), tree(MIRROR_DIR)
    for name, data in sorted(source.items()):
        if lf(mirror.get(name)) != lf(data):
            if check:
                findings.append('.agents/skills/%s differs from the skills source: run python -I Agents/sync_skills.py' % name)
            else:
                write_bytes(os.path.join(MIRROR_DIR, *name.split('/')), data)
                print('mirrored .agents/skills/%s' % name)
    for name in sorted(set(mirror) - set(source)):
        if check:
            findings.append('.agents/skills/%s is not in the skills source: run python -I Agents/sync_skills.py' % name)
        else:
            os.remove(os.path.join(MIRROR_DIR, *name.split('/')))
            print('removed .agents/skills/%s' % name)
    if not check and os.path.isdir(MIRROR_DIR):
        for root, dirs, files in os.walk(MIRROR_DIR, topdown=False):
            if not dirs and not files and root != MIRROR_DIR:
                os.rmdir(root)
    return findings


def check_all(skills_dir=SKILLS_DIR, tools_dir=TOOLS_DIR):
    tools, unparsed = registered_tools(tools_dir)
    findings = ['%s registers a tool whose name this script cannot read' % f for f in unparsed]
    if not tools:
        findings.append('no registered MCP tools found under %s' % rel(tools_dir))
    names = sorted(skill_names(skills_dir))
    if not names:
        findings.append('no skills under %s' % rel(skills_dir))
    for name in names:
        findings += check_skill(os.path.join(skills_dir, name), tools, names)
    return findings, tools, names


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument('--check', action='store_true', help='write nothing; fail when anything is out of date or invalid')
    args = ap.parse_args(argv)
    findings = sync(args.check)
    more, tools, names = check_all()
    findings += more
    for finding in findings:
        print(finding)
    print('%s: %d skills (%s), %d registered MCP tools, %d findings'
          % ('check' if args.check else 'sync', len(names), ', '.join(names), len(tools), len(findings)))
    return 1 if findings else 0


if __name__ == '__main__':
    sys.exit(main())
